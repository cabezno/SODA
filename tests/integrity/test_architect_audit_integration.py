def run(coro):
    return asyncio.get_event_loop().run_until_complete(coro)


@dataclass
class FakeDriverResponse:
    content: str
    error_code: Optional[str] = None
    tokens_input: int = 500
    tokens_output: int = 1000
    latency_ms: int = 800
    model_used: str = "claude-haiku-4-5-20251001"
    cost_usd: float = 0.03
    metadata: dict = field(default_factory=dict)


def _make_driver(contract_json: str):
    driver = MagicMock()
    driver.call = AsyncMock(return_value=FakeDriverResponse(content=contract_json))
    return driver


