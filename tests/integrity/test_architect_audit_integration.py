    def test_attempt_metadata_is_passed_to_driver(self):
        """The driver receives attempt_number and complexity metadata."""
        driver = _make_driver(_simple_contract_json())
        architect = Architect(driver)
        auditor = ContractAuditor(goal_tree={})
        loop = ContractRefinementLoop(architect, auditor, max_attempts=1)
