        # Run consistency validator separately to confirm zero errors
        v = ConsistencyValidator()
        consistency_result = run(v.validate(result.contract))
        errors = [i for i in consistency_result.issues if i.severity == "error"]
        assert errors == [], f"Consistency errors in approved contract: {errors}"

